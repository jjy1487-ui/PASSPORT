import os, xlwings as xw

def find_book(name):
    target=os.path.abspath(os.path.join('data',name)).lower()
    for app in xw.apps:
        for b in app.books:
            try:
                if os.path.abspath(b.fullname).lower()==target: return b
            except Exception: pass
    return xw.Book(os.path.abspath(os.path.join('data',name)))

