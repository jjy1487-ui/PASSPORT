def find_book(path):
    base = os.path.basename(path).lower()
    for app in xw.apps:
        for b in app.books:
            try:
                if os.path.basename(b.fullname).lower() == base:
                    return b, None
            except Exception:
                pass
    app = xw.App(visible=False); app.display_alerts = False
    return app.books.open(path), app

def main():
    bk, owned = find_book(XLSX)
    total = 0; per = {}
    for ws in bk.sheets:
        rng = ws.used_range
        n = rng.last_cell.row
        for r in range(1, n + 1):
            g = ws.range((r, 7)).value
            if g is None or str(g).strip() != "심사관":
                continue
            h = ws.range((r, 8)).value
            if h is None:
                continue
            key = str(h).strip()
            if key in MAP:
                ws.range((r, 8)).value = MAP[key]
                total += 1
                per[ws.name] = per.get(ws.name, 0) + 1
    bk.save()
    print(f"사람톤 교체 완료: 총 {total}줄")
    for sh, c in per.items():
        print(f"  {sh}: {c}")
    if owned is not None:
        owned.quit()

if __name__ == "__main__":
    main()
